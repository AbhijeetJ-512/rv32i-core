def t01_alu_table():
    t = T("t01_alu_reg", doc="Every register-register ALU op over %d x %d operand pairs, table driven." % (len(VALS), len(VALS)))
    ops = ["add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and"]
    for k, op in enumerate(ops):
        n = len(VALS) * len(VALS)
        t.i("li   s1, %d" % (k + 1), "la   t0, tbl_%s" % op, "li   t1, %d" % n)
        t.lab("Lloop_%s" % op)
        t.i("lw   a1, 0(t0)", "lw   a2, 4(t0)", "lw   a3, 8(t0)", "%-4s a4, a1, a2" % op,
            "beq  a4, a3, Lok_%s" % op, "mv   gp, t1", "j    _fail")
        t.lab("Lok_%s" % op)
        t.i("addi t0, t0, 12", "addi t1, t1, -1", "bnez t1, Lloop_%s" % op)
        t.data.append("tbl_%s:" % op)
        for a in VALS:
            for b in VALS:
                t.data.append("    .word 0x%08x, 0x%08x, 0x%08x" % (a, b, alu(op, a, b)))
    t.write()


def t02_alu_imm():
    t = T("t02_alu_imm", doc="Immediate ALU forms (addi slti sltiu xori ori andi slli srli srai), LUI and AUIPC.")
    imms = [0, 1, -1, 2047, -2048, 0x555, -0x2AB]
    vals = [0, 1, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x12345678]
    for a in vals:
        for im in imms:
            for op, f in [("addi", lambda x, i: x + i), ("slti", lambda x, i: int(s(x) < i)),
                          ("sltiu", lambda x, i: int(u(x) < u(i))), ("xori", lambda x, i: x ^ u(i)),
                          ("ori", lambda x, i: x | u(i)), ("andi", lambda x, i: x & u(i))]:
                t.i("li   t0, 0x%08x" % a, "%-5s t1, t0, %d" % (op, im))
                t.chk("t1", f(a, im))
        for sh in (0, 1, 5, 16, 31):
            for op, f in [("slli", lambda x, h: x << h), ("srli", lambda x, h: u(x) >> h), ("srai", lambda x, h: s(x) >> h)]:
                t.i("li   t0, 0x%08x" % a, "%-5s t1, t0, %d" % (op, sh))
                t.chk("t1", f(a, sh))
    for imm in (0, 1, 0x12345, 0xFFFFF, 0x80000, 0x7FFFF):
        t.i("lui  t1, 0x%x" % imm)
        t.chk("t1", imm << 12)
    t.lab("Lauipc")
    t.i("auipc t1, 0", "la   t2, Lauipc")
    t.n += 1
    t.i("beq  t1, t2, Lc%d" % t.n, "li   gp, %d" % t.n, "j    _fail")
    t.lab("Lc%d" % t.n)
    t.lab("Lauipc2")
    t.i("auipc t1, 1", "la   t2, Lauipc2", "li   t3, 4096", "add  t2, t2, t3")
    t.n += 1
    t.i("beq  t1, t2, Lc%d" % t.n, "li   gp, %d" % t.n, "j    _fail")
    t.lab("Lc%d" % t.n)
    t.write()


def t03_mem():
    t = T("t03_loads_stores", doc="All load/store sizes, every byte lane, sign/zero extension, neighbours untouched.")
    word = 0x89ABCDEF
    b = [(word >> (8 * i)) & 0xFF for i in range(4)]
    t.data += ["buf:", "    .word 0x%08x, 0x11223344, 0x55667788, 0x99AABBCC, 0, 0, 0, 0" % word]
    t.i("la   s0, buf", "li   s1, 0")
    for off in range(4):
        t.i("lbu  t1, %d(s0)" % off); t.chk("t1", b[off])
        t.i("lb   t1, %d(s0)" % off); t.chk("t1", b[off] - 256 if b[off] & 0x80 else b[off])
    for off in (0, 2):
        h = b[off] | (b[off + 1] << 8)
        t.i("lhu  t1, %d(s0)" % off); t.chk("t1", h)
        t.i("lh   t1, %d(s0)" % off); t.chk("t1", h - 65536 if h & 0x8000 else h)
    t.i("lw   t1, 0(s0)"); t.chk("t1", word)
    t.i("lw   t1, 4(s0)"); t.chk("t1", 0x11223344)
    # byte stores into a clean word, one lane at a time
    exp = 0
    for off in range(4):
        v = 0xA0 + off * 0x11
        t.i("li   t0, 0x%x" % v, "sb   t0, %d(s0)" % (16 + off), "lw   t1, 16(s0)")
        exp |= v << (8 * off)
        t.chk("t1", exp)
    # halfword stores
    t.i("li   t0, 0xBEEF", "sh   t0, 20(s0)", "li   t0, 0xCAFE", "sh   t0, 22(s0)", "lw   t1, 20(s0)")
    t.chk("t1", 0xCAFEBEEF)
    # a word store, then a byte store must leave the other three bytes alone, and a store must not touch the next word
    t.i("li   t0, 0x01020304", "sw   t0, 24(s0)", "li   t0, 0xFF", "sb   t0, 25(s0)", "lw   t1, 24(s0)", "lw   t2, 28(s0)")
    t.chk("t1", 0x0102FF04)
    t.chk("t2", 0)
    # negative offsets and a base register that moves
    t.i("addi s2, s0, 32", "li   t0, 0x5A5A5A5A", "sw   t0, -4(s2)", "lw   t1, 28(s0)")
    t.chk("t1", 0x5A5A5A5A)
    # store then immediately load the same address (data forwarded through memory, no hazard hardware involved)
    t.i("li   t0, 0x13572468", "sw   t0, 0(s0)", "lw   t1, 0(s0)")
    t.chk("t1", 0x13572468)
    t.i("li   t0, 0x80", "sb   t0, 3(s0)", "lb   t1, 3(s0)", "lbu  t2, 3(s0)")
    t.chk("t1", -128)
    t.chk("t2", 0x80)
    t.write()


def t04_branches():
    t = T("t04_branches", doc="All six conditional branches, taken and not taken, signed/unsigned boundaries.")
    pairs = [(0, 0), (1, 2), (2, 1), (0xFFFFFFFF, 1), (1, 0xFFFFFFFF), (0x80000000, 0x7FFFFFFF), (0x7FFFFFFF, 0x80000000),
             (0xFFFFFFFF, 0xFFFFFFFF), (5, 5), (0x80000000, 0x80000000), (0, 0x80000000), (0x80000000, 0)]
    taken = {"beq": lambda a, b: a == b, "bne": lambda a, b: a != b, "blt": lambda a, b: s(a) < s(b),
             "bge": lambda a, b: s(a) >= s(b), "bltu": lambda a, b: a < b, "bgeu": lambda a, b: a >= b}
    n = 0
    for op, f in taken.items():
        for a, b in pairs:
            n += 1
            t.i("li   t0, 0x%08x" % a, "li   t1, 0x%08x" % b, "%-4s t0, t1, Lt%d" % (op, n))
            if f(a, b):                      # must be taken: falling through is the failure
                t.i("li   gp, %d" % n, "j    _fail")
                t.lab("Lt%d" % n)
            else:                            # must fall through: the taken target is the failure
                t.i("j    Lg%d" % n)
                t.lab("Lt%d" % n)
                t.i("li   gp, %d" % n, "j    _fail")
                t.lab("Lg%d" % n)
    t.n = n
    # a counted loop: sum 1..100 = 5050 (backward branch taken 99 times, falls through once)
    t.i("li   t0, 0", "li   t1, 100")
    t.lab("Lsum")
    t.i("add  t0, t0, t1", "addi t1, t1, -1", "bnez t1, Lsum")
    t.chk("t0", 5050)
    # nested loops: 7 x 9 = 63
    t.i("li   t0, 0", "li   t2, 7")
    t.lab("Louter")
    t.i("li   t1, 9")
    t.lab("Linner")
    t.i("addi t0, t0, 1", "addi t1, t1, -1", "bnez t1, Linner", "addi t2, t2, -1", "bnez t2, Louter")
    t.chk("t0", 63)
    # loop trip counts 1, 2, 3 (a backward branch that is taken 0, 1, 2 times)
    for trips in (1, 2, 3):
        t.i("li   t0, 0", "li   t1, %d" % trips)
        t.lab("Ltrip%d" % trips)
        t.i("addi t0, t0, 1", "addi t1, t1, -1", "bnez t1, Ltrip%d" % trips)
        t.chk("t0", trips)
    t.write()


def t05_raw():
    t = T("t05_raw_hazards", doc="RAW dependences at distance 1..4 on each operand, forwarding priority, x0, store operands.")
    # distance 1 .. 4 on rs1 and on rs2
    for dist in range(1, 5):
        for operand in (1, 2):
            t.i("li   t0, 100", "li   t1, 7")
            t.i("addi t2, t0, 23")                         # producer: t2 = 123
            for _ in range(dist - 1):
                t.i("addi t5, t5, 1")                      # filler (independent)
            if operand == 1:
                t.i("add  t3, t2, t1")                     # consumer reads t2 as rs1
            else:
                t.i("add  t3, t1, t2")                     # ... as rs2
            t.chk("t3", 130)
    # both operands produced by the two immediately preceding instructions
    t.i("li   t0, 3", "li   t1, 4", "add  t2, t0, t0", "add  t3, t1, t1", "add  t4, t2, t3")
    t.chk("t4", 14)
    # same register written twice back to back: the YOUNGER value must win (MEM-stage forward beats WB-stage forward)
    t.i("addi t2, x0, 1", "addi t2, x0, 2", "add  t3, t2, t2")
    t.chk("t3", 4)
    t.i("addi t2, x0, 5", "addi t2, t2, 1", "addi t2, t2, 1", "addi t2, t2, 1", "add  t3, t2, t2")
    t.chk("t3", 16)
    # writer in WB and a different, younger writer in MEM, consumer uses both registers
    t.i("li   t0, 11", "li   t1, 22", "addi t0, t0, 1", "addi t1, t1, 1", "sub  t2, t1, t0")
    t.chk("t2", 11)
    # x0: writes are discarded and a following reader sees zero (no forwarding of a discarded write)
    t.i("addi x0, x0, 77", "add  t3, x0, x0")
    t.chk("t3", 0)
    t.i("li   t0, 9", "add  x0, t0, t0", "add  t3, x0, t0")
    t.chk("t3", 9)
    t.i("lui  x0, 0x12345", "auipc x0, 1", "jal  x0, Lx0j")
    t.lab("Lx0j")
    t.i("add  t3, x0, x0")
    t.chk("t3", 0)
    # store data and store address come from the immediately preceding instruction
    t.i("la   s0, scratch", "li   t0, 0x0BADF00D", "addi t1, t0, 1", "sw   t1, 0(s0)", "lw   t2, 0(s0)")
    t.chk("t2", 0x0BADF00E)
    t.i("addi s1, s0, 8", "li   t0, 0x77", "sw   t0, 0(s1)", "lw   t2, 8(s0)")
    t.chk("t2", 0x77)
    # a long dependence chain: each result feeds the next instruction: fib-style doubling
    t.i("li   t0, 1")
    for _ in range(20):
        t.i("add  t0, t0, t0")
    t.chk("t0", 1 << 20)
    # comparator operands forwarded: branch right after the producers of both its operands
    t.i("li   t0, 5", "li   t1, 5", "addi t0, t0, 1", "addi t1, t1, 1", "beq  t0, t1, Lbf1", "li   gp, 9001", "j    _fail")
    t.lab("Lbf1")
    t.i("li   t0, 5", "li   t1, 6", "addi t0, t0, 1", "addi t1, t1, 2", "bne  t0, t1, Lbf2", "li   gp, 9002", "j    _fail")
    t.lab("Lbf2")
    t.data += ["scratch:", "    .word 0, 0, 0, 0"]
    t.write()


def t06_load_use():
    t = T("t06_load_use", doc="A load followed by a consumer in every operand position, and at distance 1, 2 and 3.")
    t.data += ["tbl:", "    .word 0x00000010, 0x00000003, 0x12345678, 0, 0, 0, 0, 0",
               "ptrs:", "    .word ptr1, ptr2, ptr3, 0x0000AAAA", "ptr1:", "    .word ptr2", "ptr2:", "    .word ptr3",
               "ptr3:", "    .word 0xC0FFEE00", "out:", "    .word 0, 0, 0, 0"]
    t.i("la   s0, tbl")
    t.i("lw   t0, 0(s0)", "addi t1, t0, 1");           t.chk("t1", 0x11)           # consumer as rs1
    t.i("lw   t0, 4(s0)", "add  t1, t1, t0");          t.chk("t1", 0x14)           # consumer as rs2
    t.i("lw   t0, 0(s0)", "lw   t1, 4(s0)", "add  t2, t0, t1");  t.chk("t2", 0x13)   # distance 2 for t0, distance 1 for t1
    t.i("lw   t0, 0(s0)", "add  t2, t0, t0");          t.chk("t2", 0x20)           # both operands from the load
    t.i("lw   t0, 0(s0)", "nop", "addi t1, t0, 1");    t.chk("t1", 0x11)           # distance 2
    t.i("lw   t0, 0(s0)", "nop", "nop", "addi t1, t0, 2");  t.chk("t1", 0x12)      # distance 3
    # store data straight after the load, then store address straight after the load
    t.i("la   s1, out", "lw   t0, 8(s0)", "sw   t0, 0(s1)", "lw   t2, 0(s1)");   t.chk("t2", 0x12345678)
    # &out is stored to memory, loaded back into t3 and used AT ONCE as the base address of a store (load -> store address)
    t.i("la   t0, out", "sw   t0, 4(s1)", "lw   t3, 4(s1)", "sw   s0, 0(t3)", "lw   t4, 0(s1)")
    t.chk("t4", 0x8000)  # s0 = &tbl, the first data label = data base 0x8000
    # pointer chasing: each load's address is the previous load's result
    t.i("la   t0, ptrs", "lw   t1, 0(t0)", "lw   t2, 0(t1)", "lw   t3, 0(t2)", "lw   t4, 0(t3)")
    t.chk("t4", 0xC0FFEE00)
    # load feeding a branch operand (rs1 and rs2) and a JALR target
    t.i("lw   t0, 0(s0)", "li   t1, 16", "beq  t0, t1, Lb1", "li   gp, 9101", "j    _fail")
    t.lab("Lb1")
    t.i("li   t1, 16", "lw   t0, 0(s0)", "bne  t1, t0, Lb2f", "j    Lb2")
    t.lab("Lb2f")
    t.i("li   gp, 9102", "j    _fail")
    t.lab("Lb2")
    t.i("la   t0, Ljt", "sw   t0, 0(s1)", "lw   t1, 0(s1)", "jalr x0, 0(t1)", "li   gp, 9103", "j    _fail")
    t.lab("Ljt")
    # a load into x0 followed by a reader of x0 must see 0 (and must not deadlock the stall logic)
    t.i("lw   x0, 0(s0)", "add  t1, x0, x0")
    t.chk("t1", 0)
    # load, dependent load, dependent ALU, dependent store in a row
    t.i("la   t0, ptrs", "lw   t1, 12(t0)", "addi t2, t1, 1", "sw   t2, 8(s1)", "lw   t3, 8(s1)")
    t.chk("t3", 0xAAAB)
    t.write()


def t07_control():
    t = T("t07_control_flow", doc="Wrong-path squash, JAL/JALR link values, call/return nesting, branch after producers.")
    t.data += ["mark:", "    .word 0, 0, 0, 0"]
    t.i("la   s0, mark", "li   s4, 0")
    # taken forward branch: the two following instructions must not execute (register write and store)
    t.i("li   t0, 1", "bnez t0, Lskip1", "addi s4, s4, 100", "sw   t0, 0(s0)")
    t.lab("Lskip1")
    t.chk("s4", 0)
    t.i("lw   t1, 0(s0)")
    t.chk("t1", 0)
    # JAL: link value is pc+4, the skipped instructions do not execute
    t.lab("Ljal")
    t.i("jal  t2, Lj1", "addi s4, s4, 100", "sw   t0, 4(s0)")
    t.lab("Lj1")
    t.i("la   t3, Ljal", "addi t3, t3, 4")
    t.chk("s4", 0)
    t.n += 1
    t.i("beq  t2, t3, Lc%d" % t.n, "li   gp, %d" % t.n, "j    _fail")
    t.lab("Lc%d" % t.n)
    t.i("lw   t1, 4(s0)")
    t.chk("t1", 0)
    # JALR: target = rs1 + imm with bit 0 cleared; link = pc+4
    t.i("la   t0, Ljr", "addi t0, t0, -3")           # target arrives as Ljr-3+3(imm)... use imm 3
    t.lab("Ljr0")
    t.i("jalr t4, 3(t0)", "addi s4, s4, 100", "sw   t0, 8(s0)")
    t.lab("Ljr")
    t.i("la   t5, Ljr0", "addi t5, t5, 4")
    t.chk("s4", 0)
    t.n += 1
    t.i("beq  t4, t5, Lc%d" % t.n, "li   gp, %d" % t.n, "j    _fail")
    t.lab("Lc%d" % t.n)
    t.i("lw   t1, 8(s0)")
    t.chk("t1", 0)
    # JAL to the very next instruction
    t.i("jal  t2, Lnext")
    t.lab("Lnext")
    t.i("addi s4, s4, 1")
    t.chk("s4", 1)
    # call / return nesting 3 deep (ra saved on a stack held in memory)
    t.i("la   sp, stack_top", "li   s5, 0", "call Lf1", "j    Ldone_calls")
    t.lab("Lf1")
    t.i("addi sp, sp, -4", "sw   ra, 0(sp)", "addi s5, s5, 1", "call Lf2", "addi s5, s5, 100", "lw   ra, 0(sp)", "addi sp, sp, 4", "ret")
    t.lab("Lf2")
    t.i("addi sp, sp, -4", "sw   ra, 0(sp)", "addi s5, s5, 2", "call Lf3", "addi s5, s5, 100", "lw   ra, 0(sp)", "addi sp, sp, 4", "ret")
    t.lab("Lf3")
    t.i("addi s5, s5, 4", "ret")
    t.lab("Ldone_calls")
    t.chk("s5", 207)
    # branch whose operands come straight from the preceding instructions, taken and not taken
    t.i("li   t0, 3", "addi t0, t0, 1", "addi t1, t0, 0", "beq  t0, t1, Lbt", "li   gp, 9301", "j    _fail")
    t.lab("Lbt")
    t.i("li   t0, 3", "addi t1, t0, 1", "bne  t0, t1, Lbt2", "li   gp, 9302", "j    _fail")
    t.lab("Lbt2")
    # back-to-back branches
    t.i("li   t0, 1", "li   t1, 2", "blt  t0, t1, Lbb1", "li   gp, 9303", "j    _fail")
    t.lab("Lbb1")
    t.i("blt  t1, t0, Lbb_bad", "bge  t1, t0, Lbb2", "li   gp, 9304", "j    _fail")
    t.lab("Lbb_bad")
    t.i("li   gp, 9305", "j    _fail")
    t.lab("Lbb2")
    # a taken branch immediately followed by another taken branch, then a JAL
    t.i("beq  x0, x0, Lc1x", "li   gp, 9306", "j    _fail")
    t.lab("Lc1x")
    t.i("beq  x0, x0, Lc2x", "li   gp, 9307", "j    _fail")
    t.lab("Lc2x")
    t.i("jal  x0, Lc3x", "li   gp, 9308", "j    _fail")
    t.lab("Lc3x")
    t.data += [".align 2", "    .space 64", "stack_top:", "    .word 0"]
    t.write()


def t08_traps():
    # each trap test is its own program: the core stops at the trap, so only one per file
    def trap(name, doc, before, instr_lines, expect="trap"):
        t = T(name, expect=expect, doc=doc)
        t.i("la   s0, mem1", "li   s1, 0x11111111", "sw   s1, 0(s0)", "li   s2, 0x22222222", "sw   s2, 4(s0)")
        t.i(*before)
        t.i(*instr_lines)
        # younger instructions that must NOT execute: a register write and a store
