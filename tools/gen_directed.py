def t10_loop_on_load():
    t = T("t10_loop_on_load", doc="Backward branches whose operand comes straight from the load before them (load-use stall on a "
                                  "branch that BP_MODE=1 predicts taken), and a stalled JAL-free loop with a store in the body.")
    t.data += ["lst:", "    .word 5, 4, 3, 2, 1, 0, 0xDEAD", "cnt:", "    .word 0"]
    # walk a zero-terminated list: the branch depends on the load immediately before it
    t.i("la   a0, lst", "li   a1, 0")
    t.lab("Lw")
    t.i("lw   t0, 0(a0)", "addi a0, a0, 4", "add  a1, a1, t0")
    t.i("lw   t1, -4(a0)", "bnez t1, Lw")           # load, then a backward branch on the loaded value: stall + predicted taken
    t.chk("a1", 15)
    # the same with the loaded value used as the second branch operand
    t.i("la   a0, lst", "li   a1, 0", "li   t2, 0")
    t.lab("Lw2")
    t.i("lw   t0, 0(a0)", "addi a0, a0, 4", "addi a1, a1, 1", "lw   t1, -4(a0)", "bne  t2, t1, Lw2")
    t.chk("a1", 6)
    # a counter that lives in memory: load, decrement, store, load, backward branch
    t.i("la   s0, cnt", "li   t0, 7", "sw   t0, 0(s0)", "li   a2, 0")
    t.lab("Lm")
    t.i("lw   t0, 0(s0)", "addi t0, t0, -1", "sw   t0, 0(s0)", "addi a2, a2, 2", "lw   t1, 0(s0)", "bnez t1, Lm")
    t.chk("a2", 14)
    # a backward branch that is NOT taken right after a load (mispredicted under BTFN) followed by a dependent consumer
    t.i("la   s0, cnt", "li   t0, 0", "sw   t0, 0(s0)", "li   a3, 1")
    t.lab("Lnt")
    t.i("lw   t1, 0(s0)", "bnez t1, Lnt", "addi a3, a3, 41")
    t.chk("a3", 42)
    t.write()


