#!/usr/bin/env python3
"""gen_directed.py - writes the directed, self-checking RV32I tests into tests/asm/.

Every expected value in these tests is computed HERE, by plain Python arithmetic on the operands, not by the ISS and
not by the RTL: the test programs therefore check the RTL against a third, independent oracle (the ISS comparison
checks the RTL against the ISS on the same programs). A failed check leaves its number in gp (x3) and ends the program
with a0 = 1.

    python3 tools/gen_directed.py        # rewrites tests/asm/t0*.S and t1*.S (generated files carry a header)
"""
import os

M = 0xFFFFFFFF
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "asm")


def u(v):
    return v & M


def s(v):
    v &= M
    return v - (1 << 32) if v & 0x80000000 else v


def alu(op, a, b):
    a, b = u(a), u(b)
    sh = b & 31
    return u({
        "add": a + b, "sub": a - b, "sll": a << sh, "slt": int(s(a) < s(b)), "sltu": int(a < b),
        "xor": a ^ b, "srl": a >> sh, "sra": s(a) >> sh, "or": a | b, "and": a & b,
    }[op])


VALS = [0, 1, 2, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x12345678, 0xDEADBEEF, 31, 0x0000FFFF]


class T:
    def __init__(self, name, expect="pass", doc=""):
        self.name, self.expect, self.n = name, expect, 0
        self.body, self.data = [], []
        self.doc = doc

    def i(self, *ins):
        for x in ins:
            self.body.append("    " + x)

    def lab(self, name):
        self.body.append(name + ":")

    def chk(self, reg, val):
        """Fail (gp = check number) unless reg == val."""
        self.n += 1
        self.i("li   t6, 0x%08x" % u(val), "beq  %s, t6, Lc%d" % (reg, self.n), "li   gp, %d" % self.n, "j    _fail")
        self.lab("Lc%d" % self.n)

    def write(self):
        head = ["# GENERATED by tools/gen_directed.py - do not edit by hand.", "# %s" % self.doc]
        if self.expect != "pass":
            head.append("# EXPECT: %s" % self.expect)
        body = list(self.body)
        if self.expect == "pass":
            body.append("    j    _pass")
        txt = "\n".join(head + body)
        if self.data:
            txt += "\n.data\n" + "\n".join(self.data)
        with open(os.path.join(OUT, self.name + ".S"), "w") as f:
            f.write(txt + "\n")


