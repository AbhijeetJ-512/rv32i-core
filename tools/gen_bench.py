def matmul():
    n = 6
    A = [[rnd.randint(0, 15) for _ in range(n)] for _ in range(n)]
    B = [[rnd.randint(0, 15) for _ in range(n)] for _ in range(n)]
    C = [[sum(A[i][k] * B[k][j] for k in range(n)) for j in range(n)] for i in range(n)]
    chk = sum(sum(r) for r in C) & M
    flatA = [v for r in A for v in r]
    flatB = [v for r in B for v in r]
    code = ["    li   s0, %d" % n, "    la   s1, matA", "    la   s2, matB", "    la   s3, matC", "    li   s4, 0",
            "Li:", "    li   s5, 0",
            "Lj:", "    li   s6, 0", "    li   s7, 0",                                # s7 accumulates C[i][j]
            "Lk:",
            # a0 = A[i][k]  at matA + 4*(i*n + k)
            "    mv   t0, s4", "    li   t1, 0", "    mv   t2, s0",
            "Lim:", "    beqz t2, Limd", "    add  t1, t1, t0", "    addi t2, t2, -1", "    j    Lim",    # t1 = i*n
            "Limd:", "    add  t1, t1, s6", "    slli t1, t1, 2", "    add  t1, t1, s1", "    lw   a0, 0(t1)",
            # a1 = B[k][j]  at matB + 4*(k*n + j)
            "    mv   t0, s6", "    li   t1, 0", "    mv   t2, s0",
            "Lkm:", "    beqz t2, Lkmd", "    add  t1, t1, t0", "    addi t2, t2, -1", "    j    Lkm",
            "Lkmd:", "    add  t1, t1, s5", "    slli t1, t1, 2", "    add  t1, t1, s2", "    lw   a1, 0(t1)",
            "    call Lmul", "    add  s7, s7, a2",
            "    addi s6, s6, 1", "    blt  s6, s0, Lk",
            "    li   t1, 0", "    mv   t0, s4", "    mv   t2, s0",
            "Lcm:", "    beqz t2, Lcmd", "    add  t1, t1, t0", "    addi t2, t2, -1", "    j    Lcm",
            "Lcmd:", "    add  t1, t1, s5", "    slli t1, t1, 2", "    add  t1, t1, s3", "    sw   s7, 0(t1)",
            "    addi s5, s5, 1", "    blt  s5, s0, Lj", "    addi s4, s4, 1", "    blt  s4, s0, Li",
            # checksum of C
            "    li   t0, %d" % (n * n), "    mv   t1, s3", "    li   a3, 0",
            "Lsum:", "    lw   t2, 0(t1)", "    add  a3, a3, t2", "    addi t1, t1, 4", "    addi t0, t0, -1", "    bnez t0, Lsum",
            "    li   t1, 0x%08x" % chk, "    beq  a3, t1, Lok", "    li   gp, 1", "    j    _fail",
            # a2 = a0 * a1 by shift-and-add (a0, a1 unsigned, small)
            "Lmul:", "    li   a2, 0", "    mv   t3, a0", "    mv   t4, a1",
            "Lmulloop:", "    beqz t4, Lmulret", "    andi t5, t4, 1", "    beqz t5, Lmulskip", "    add  a2, a2, t3",
            "Lmulskip:", "    slli t3, t3, 1", "    srli t4, t4, 1", "    j    Lmulloop",
            "Lmulret:", "    ret",
            "Lok:"]
    # Lok must be reached from the checksum compare: place it before Lmul's body by restructuring
    code.remove("Lok:")
    idx = code.index("    li   gp, 1")
    code.insert(idx - 1, "    j    Lok2")        # unreachable guard so the label order stays simple
    code = [c for c in code if c != "    j    Lok2"]
    code[code.index("    beq  a3, t1, Lok")] = "    beq  a3, t1, Lok"
    # put Lok right after the failing jump, and jump over the subroutine
    j = code.index("    j    _fail")
    code.insert(j + 1, "Lok:")
    code.insert(j + 2, "    j    _pass")
    write("b_matmul", "%dx%d integer matrix multiply with a software shift-add multiply called per element: call/ret, loops, loads" % (n, n),
          code, words("matA", flatA) + words("matB", flatB) + ["matC:", "    .space %d" % (4 * n * n)])


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for f in (fib, memcpy, bubblesort, sieve, crc32, listwalk, matmul):
        f()
    print("generated", len(os.listdir(OUT)), "benchmarks in", os.path.normpath(OUT))
