#!/usr/bin/env python3
"""gen_bench.py - writes the self-checking benchmark programs into tests/bench/.

The expected result of each program is computed here with Python (zlib, plain loops), independently of the ISS and the
RTL; a program that computes another value ends with a0 = 1. They exist to give the CPI figures a workload: a mix of
dependent arithmetic (fib), streaming loads and stores (memcpy), data-dependent branches (bubble sort, CRC-32, sieve),
pointer chasing (list walk) and call/return with software multiply (matmul).
"""
import os
import random
import zlib

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "bench")
M = 0xFFFFFFFF
rnd = random.Random(2026)


def words(label, ws):
    lines = [label + ":"]
    for i in range(0, len(ws), 8):
        lines.append("    .word " + ", ".join("0x%08x" % (w & M) for w in ws[i:i + 8]))
    return lines


def bytes_(label, bs):
    lines = [label + ":"]
    for i in range(0, len(bs), 16):
        lines.append("    .byte " + ", ".join("0x%02x" % b for b in bs[i:i + 16]))
    return lines


def write(name, doc, code, data):
    with open(os.path.join(OUT, name + ".S"), "w") as f:
        f.write("# GENERATED by tools/gen_bench.py - %s\n" % doc)
        f.write("\n".join(code) + "\n    j    _pass\n.data\n" + "\n".join(data) + "\n")


def fib():
    n = 90
    a, b = 0, 1
    for _ in range(n):
        a, b = b, (a + b) & M
    code = ["    li   t0, %d" % n, "    li   a1, 0", "    li   a2, 1"]
    code += ["Lf:", "    add  a3, a1, a2", "    mv   a1, a2", "    mv   a2, a3", "    addi t0, t0, -1", "    bnez t0, Lf",
             "    li   t1, 0x%08x" % a, "    beq  a1, t1, Lok", "    li   gp, 1", "    j    _fail", "Lok:"]
    write("b_fib", "iterative Fibonacci mod 2^32 (fib(%d)): a dependent add chain and one loop branch" % n, code, [".word 0"])


def memcpy():
    n = 256
    src = [rnd.getrandbits(32) for _ in range(n)]
    code = ["    la   a0, src", "    la   a1, dst", "    li   t0, %d" % n,
            "Lc:", "    lw   t1, 0(a0)", "    sw   t1, 0(a1)", "    addi a0, a0, 4", "    addi a1, a1, 4", "    addi t0, t0, -1", "    bnez t0, Lc",
            "    la   a1, dst", "    li   t0, %d" % n, "    li   a2, 0",
            "Ls:", "    lw   t1, 0(a1)", "    add  a2, a2, t1", "    addi a1, a1, 4", "    addi t0, t0, -1", "    bnez t0, Ls",
            "    li   t1, 0x%08x" % (sum(src) & M), "    beq  a2, t1, Lok", "    li   gp, 1", "    j    _fail", "Lok:"]
    write("b_memcpy", "copy %d words then checksum the copy: load, store and a load-use pair per iteration" % n, code,
          words("src", src) + ["dst:", "    .space %d" % (4 * n)])


def bubblesort():
    n = 48
    a = [rnd.getrandbits(16) for _ in range(n)]
    srt = sorted(a)
    chk = sum(i * v for i, v in enumerate(srt)) & M
    code = ["    li   s0, %d" % n, "    la   s1, arr",
            "Lout:", "    addi s2, s0, -1", "    beqz s2, Ldone", "    mv   t0, s1", "    li   t1, 0",
            "Lin:", "    lw   a0, 0(t0)", "    lw   a1, 4(t0)", "    bge  a1, a0, Lnoswap",
            "    sw   a1, 0(t0)", "    sw   a0, 4(t0)",
            "Lnoswap:", "    addi t0, t0, 4", "    addi t1, t1, 1", "    blt  t1, s2, Lin",
            "    addi s0, s0, -1", "    j    Lout",
            "Ldone:", "    la   t0, arr", "    li   t1, 0", "    li   a2, 0", "    li   t2, %d" % n,
            "Lsum:", "    lw   a0, 0(t0)", "    mv   a3, t1", "    li   a4, 0",            # a4 = i * a0 by repeated addition of i
            "Lmul:", "    beqz a3, Lmuld", "    add  a4, a4, a0", "    addi a3, a3, -1", "    j    Lmul",
            "Lmuld:", "    add  a2, a2, a4", "    addi t0, t0, 4", "    addi t1, t1, 1", "    blt  t1, t2, Lsum",
            "    li   t1, 0x%08x" % chk, "    beq  a2, t1, Lok", "    li   gp, 1", "    j    _fail", "Lok:"]
    write("b_bubblesort", "bubble sort of %d half-words then a position-weighted checksum: data-dependent branches, load-use, stores" % n, code, words("arr", a))


def sieve():
    n = 2000
    flags = [1] * (n + 1)
    flags[0] = flags[1] = 0
    for i in range(2, int(n ** 0.5) + 1):
        if flags[i]:
            for j in range(i * i, n + 1, i):
                flags[j] = 0
    count = sum(flags)
    code = ["    la   s0, flags", "    li   s1, %d" % (n + 1), "    li   t0, 0", "    li   t1, 1",
            "Linit:", "    add  t2, s0, t0", "    sb   t1, 0(t2)", "    addi t0, t0, 1", "    blt  t0, s1, Linit",
            "    sb   x0, 0(s0)", "    sb   x0, 1(s0)", "    li   t0, 2",
            "Lp:", "    mul_free_check:", "    mv   a0, t0", "    mv   a1, t0", "    li   a2, 0",     # a2 = t0 * t0 by repeated add
            "Lsq:", "    add  a2, a2, t0", "    addi a1, a1, -1", "    bnez a1, Lsq",
            "    bge  a2, s1, Lcount", "    add  t2, s0, t0", "    lbu  t3, 0(t2)", "    beqz t3, Lnext",
            "Lmark:", "    add  t2, s0, a2", "    sb   x0, 0(t2)", "    add  a2, a2, t0", "    blt  a2, s1, Lmark",
            "Lnext:", "    addi t0, t0, 1", "    j    Lp",
            "Lcount:", "    li   t0, 0", "    li   a3, 0",
            "Lc2:", "    add  t2, s0, t0", "    lbu  t3, 0(t2)", "    add  a3, a3, t3", "    addi t0, t0, 1", "    blt  t0, s1, Lc2",
            "    li   t1, %d" % count, "    beq  a3, t1, Lok", "    li   gp, 1", "    j    _fail", "Lok:"]
    code = [c for c in code if "mul_free_check" not in c]
    write("b_sieve", "sieve of Eratosthenes up to %d (%d primes): byte loads and stores, nested loops" % (n, count), code,
          ["flags:", "    .space %d" % (n + 4)])


def crc32():
    n = 192
    data = bytes(rnd.getrandbits(8) for _ in range(n))
    crc = zlib.crc32(data) & M
    code = ["    la   a0, buf", "    li   a1, %d" % n, "    li   a2, 0xFFFFFFFF", "    li   s0, 0xEDB88320",
            "Lbyte:", "    lbu  t0, 0(a0)", "    xor  a2, a2, t0", "    li   t1, 8",
            "Lbit:", "    andi t2, a2, 1", "    srli a2, a2, 1", "    beqz t2, Lnox", "    xor  a2, a2, s0",
            "Lnox:", "    addi t1, t1, -1", "    bnez t1, Lbit", "    addi a0, a0, 1", "    addi a1, a1, -1", "    bnez a1, Lbyte",
            "    not  a2, a2", "    li   t1, 0x%08x" % crc, "    beq  a2, t1, Lok", "    li   gp, 1", "    j    _fail", "Lok:"]
    write("b_crc32", "bitwise CRC-32 over %d bytes (checked against zlib.crc32): shifts, xors, a data-dependent branch per bit" % n, code,
          bytes_("buf", list(data)))


def listwalk():
    n = 160
    order = list(range(n))
    rnd.shuffle(order)
    vals = [rnd.getrandbits(20) for _ in range(n)]
    # node i at nodes + 8*i: [next_address, value]; the walk visits nodes in the shuffled order
    base = 0x8000
    nxt = {}
    for k in range(n - 1):
        nxt[order[k]] = order[k + 1]
    nxt[order[-1]] = None
    data = ["nodes:"]
    for i in range(n):
        link = ("nodes + %d" % (8 * nxt[i])) if nxt[i] is not None else "0"
