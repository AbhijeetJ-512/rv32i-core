#!/usr/bin/env python3
"""readme_results.py - splice the measured results into README.md between the RESULTS markers.

Nothing in the spliced block is typed by hand: each part is the verbatim content of a file in results/ that a make target wrote.
A part whose file is missing is replaced by NOT YET MEASURED plus the command that produces it.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = lambda f: os.path.join(ROOT, "results", f)  # noqa: E731


def read(f, n=None):
    if not os.path.exists(R(f)):
        return None
    t = open(R(f)).read().rstrip("\n")
    return "\n".join(t.splitlines()[:n]) if n else t


def part(title, f, cmd, n=None, fence=True):
    body = read(f, n)
    if body is None:
        return "### %s\n\nNOT YET MEASURED - run `%s`.\n" % (title, cmd)
    return "### %s\n\nFrom `results/%s` (`%s`).\n\n%s\n" % (title, f, cmd, ("```text\n%s\n```" % body) if fence else body)


def main():
    p = os.path.join(ROOT, "README.md")
    txt = open(p).read()
    tot = 0
    if os.path.exists(R("random.txt")):
        tot = sum(int(m.group(1)) for m in re.finditer(r"(\d+) insns", open(R("random.txt")).read()))
    blocks = [
        part("Directed tests (lock-step against the ISS, both BP modes)", "directed.txt", "make test", n=1),
        "### Constrained-random programs\n\n%s\n" % ("`results/random.txt` (`make rand NRAND=200`): `%s`; %d instructions retired and compared in total." % (read("random.txt", 1), tot) if tot else "NOT YET MEASURED - run `make rand`."),
        part("Coverage (merged: directed + benchmarks + random, both BP modes)", "coverage_summary.txt", "make cov"),
        part("Mutation run (checks of the checks)", "mutants.txt", "make mutants", n=7),
        part("Formal: riscv-formal bounded checks (current core)", "formal.txt", "make formal"),
        part("Formal: the same checks on the core before the misaligned-target fix", "formal_as_found.txt", "formal/run_as_found.sh"),
        part("CPI and bubble sources", "cpi.md", "make bench", fence=False),
        part("Synthesis and timing", "ppa.md", "make ppa", fence=False),
        part("Execution time: cycles x T_min", "performance.md", "make perf", fence=False),
        part("Place and route (OpenROAD)", "pnr.md", "make pnr", fence=False),
    ]
    new = "<!-- BEGIN RESULTS (generated by scripts/readme_results.py from results/; do not edit by hand) -->\n\n" + "\n".join(blocks) + "\n<!-- END RESULTS -->"
    txt2 = re.sub(r"<!-- BEGIN RESULTS.*?<!-- END RESULTS -->", lambda m: new, txt, flags=re.S)
    open(p, "w").write(txt2)
    print("README results block updated (%d characters)" % len(new))


if __name__ == "__main__":
    sys.exit(main())
